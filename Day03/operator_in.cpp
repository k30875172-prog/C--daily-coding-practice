#include <iostream>
using namespace std;

int main() {
    int a = 10; int b =10;
    //Assignment operator-->used to assign value to variables
    //int a = 3; int b = 9;
    //char d ='d';

    //Comparison operators
    cout <<"The value of a == b is"<<(a==b)<<endl;
    cout <<"The value of a != b is"<<(a!=b)<<endl;
    cout <<"The value of a <= b is"<<(a<=b)<<endl;
    cout <<"The value of a >= b is"<<(a>=b)<<endl;
    cout <<"The value of a < b  is"<<(a<b)<<endl;
    cout <<"The value of a > b is"<<(a>b)<<endl;
    return 0;    
}
